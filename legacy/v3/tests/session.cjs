const {chromium}=require('playwright');
const assert=require('assert/strict');
const fs=require('fs');
const {chromiumPath}=require('./runtime.cjs');
let checks=0;
function ok(v,m){assert.ok(v,m);checks++;}
const url='http://127.0.0.1:8765/';
(async()=>{
 const browser=await chromium.launch({executablePath:chromiumPath()||chromium.executablePath(),headless:true,args:['--no-sandbox']});
 const context=await browser.newContext();
 const page=await context.newPage();
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(url);
 await page.evaluate(()=>{localStorage.removeItem('synergy-v3-records');localStorage.removeItem('synergy-v3-tab');});
 await page.reload();
 await page.waitForFunction(()=>window.SynergyMVP&&document.getElementById('missionIndex').textContent.includes('/ 06'));
 ok(await page.evaluate(()=>window.SynergyMVP.getState().leader));
 await page.click('#start');
 await page.evaluate(()=>window.dispatchEvent(new PageTransitionEvent('pageshow',{persisted:true})));
 let state=await page.evaluate(()=>window.SynergyMVP.getState());
 ok(state.paused&&state.trial&&!state.trial.done&&!state.trial.success&&state.events.length===0,'bfcache restore must not finish the attempt');
 await page.reload();
 await page.click('#start');
 await page.click('.controls [data-action="close"]');
 await page.waitForFunction(()=>window.SynergyMVP.getState().trial.phase==='carry',{},{timeout:8000});
 await page.evaluate(()=>window.SynergyMVP.unmount());
 state=await page.evaluate(()=>window.SynergyMVP.getState());
 ok(state.events.length===1&&state.events[0].outcome==='aborted'&&state.events[0].success===false);
 await page.waitForTimeout(300);
 ok((await page.evaluate(()=>window.SynergyMVP.getState().events.length))===1);
 for(let i=0;i<100;i++){
  await page.reload();
  await page.waitForFunction(()=>window.SynergyMVP&&window.SynergyMVP.getState().events.length===1&&!window.SynergyMVP.getState().trial);
 }
 const other=await context.newPage();
 const otherErrors=[];
 other.on('pageerror',e=>otherErrors.push(e.message));
 await other.goto(url);
 await other.waitForFunction(()=>!window.SynergyMVP.getState().leader&&document.getElementById('start').disabled);
 ok((await other.locator('#storageStatus').textContent()).includes('только смотрит'));
 ok((await other.evaluate(()=>window.SynergyMVP.getState().events.length))===1);
 page.once('dialog',d=>d.accept());
 await page.click('#erase');
 await other.waitForFunction(()=>window.SynergyMVP.getState().events.length===0);
 await page.waitForTimeout(400);
 ok(await page.evaluate(()=>{const raw=localStorage.getItem('synergy-v3-records');return raw==='[]'||raw===null;}));
 ok((await other.evaluate(()=>window.SynergyMVP.getState().events.length))===0,'follower resurrected an erased event');
 const corruptContext=await browser.newContext();
 const corrupt=await corruptContext.newPage();
 const corruptErrors=[];
 corrupt.on('pageerror',e=>corruptErrors.push(e.message));
 const raw='not-json <script>window.pwned=1</script>';
 await corrupt.goto(url);
 await corrupt.evaluate(value=>localStorage.setItem('synergy-v3-records',value),raw);
 await corrupt.reload();
 await corrupt.waitForFunction(()=>document.getElementById('storageStatus').textContent.includes('исходные байты'));
 ok(!(await corrupt.evaluate(()=>window.pwned)));
 const [download]=await Promise.all([corrupt.waitForEvent('download'),corrupt.click('#export')]);
 ok(fs.readFileSync(await download.path(),'utf8')===raw);
 ok(await corrupt.evaluate(()=>localStorage.getItem('synergy-v3-records'))===raw);
 await corrupt.click('#auto');
 await corrupt.waitForFunction(()=>window.SynergyMVP.getState().trial?.done,{timeout:8000});
 ok(await corrupt.evaluate(()=>localStorage.getItem('synergy-v3-records'))===raw,'a new result overwrote the corrupt archive');
 ok(errors.length+otherErrors.length+corruptErrors.length===0,[...errors,...otherErrors,...corruptErrors].join('\n'));
 console.log(JSON.stringify({suite:'session-tabs',status:'PASS',assertions:checks,reloads:100}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
